# Python Data Types

name = "Rosna"          # String
age = 21                # Integer
height = 5.5            # Float
is_student = True       # Boolean

print("Name:", name)
print("Data type:", type(name))
print("Age:", age)
print("Data type:", type(age))
print("Height:", height)
print("Data type:", type(height))
print("Student:", is_student)
print("Data type:", type(is_student))
